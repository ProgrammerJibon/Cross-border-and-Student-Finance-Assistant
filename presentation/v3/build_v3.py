# ── Shape helpers ─────────────────────────────────────────────────────────────
def delete(sh):
    sh._element.getparent().remove(sh._element)

def clear(s):
    for sh in list(s.shapes): delete(sh)
    for el in list(s._element):
        if el.tag.endswith('}timing') or el.tag.endswith('}transition'):
            s._element.remove(el)

def rect(s, x, y, w, h, c=PANEL, radius=0.0, line_c=None, order=None):
    """Add a rectangle (sharp or rounded)."""
    if radius > 0:
        sh = s.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, Inches(x), Inches(y), Inches(w), Inches(h))
        sh.adjustments[0] = radius
    else:
        sh = s.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(x), Inches(y), Inches(w), Inches(h))
    sh.fill.solid()
    sh.fill.fore_color.rgb = rgb(c)
    sh.line.fill.background()
    if line_c:
        sh.line.color.rgb = rgb(line_c)
        sh.line.width = Pt(1.2)
    if order is not None:
        sh.name = f'reveal_{order:02d}'
    return sh

def tx(s, t, x, y, w, h, sz=18, c=WHITE, b=False, order=None, align=None, spacing=4):
    sh = s.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = sh.text_frame
    tf.word_wrap = True
    tf.margin_left = tf.margin_right = tf.margin_top = tf.margin_bottom = 0
    for i, row in enumerate(t.split('\n')):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.text = row
        p.font.name = 'Aptos'
        p.font.size = Pt(sz)
        p.font.bold = b
        p.font.color.rgb = rgb(c)
        p.space_after = Pt(spacing)
        if align is not None:
            p.alignment = align
    if order is not None:
        sh.name = f'reveal_{order:02d}'
    return sh

def pic(s, path, x, y, w, h, order=2):
    sh = s.shapes.add_picture(str(path), Inches(x), Inches(y), Inches(w), Inches(h))
    sh.name = f'reveal_{order:02d}'
    return sh

def ln(s, x1, y1, x2, y2, c=GRID, width=1.5):
    sh = s.shapes.add_connector(MSO_CONNECTOR.STRAIGHT, Inches(x1), Inches(y1), Inches(x2), Inches(y2))
    sh.line.color.rgb = rgb(c)
    sh.line.width = Pt(width)
    return sh

def dot(s, x, y, d, c):
    sh = s.shapes.add_shape(MSO_SHAPE.OVAL, Inches(x), Inches(y), Inches(d), Inches(d))
    sh.fill.solid()
    sh.fill.fore_color.rgb = rgb(c)
    sh.line.fill.background()
    return sh

def pill(s, x, y, w, h, c=TEAL, order=None):
    """A capsule/pill shape used as accent bar."""
    sh = s.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, Inches(x), Inches(y), Inches(w), Inches(h))
    sh.adjustments[0] = 0.5
    sh.fill.solid()
    sh.fill.fore_color.rgb = rgb(c)
    sh.line.fill.background()
    if order is not None: sh.name = f'reveal_{order:02d}'
    return sh

def set_bg(s):
    s.background.fill.solid()
    s.background.fill.fore_color.rgb = rgb(BG)

def notes(s, t):
    ns = s.notes_slide
    if ns.notes_text_frame is None:
        raw = '<p:sp xmlns:p="http://schemas.openxmlformats.org/presentationml/2006/main" xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main"><p:nvSpPr><p:cNvPr id="900" name="Notes body"/><p:cNvSpPr/><p:nvPr><p:ph type="body" idx="13"/></p:nvPr></p:nvSpPr><p:spPr/><p:txBody><a:bodyPr/><a:lstStyle/><a:p/></p:txBody></p:sp>'
        ns.shapes._spTree.insert_element_before(etree.fromstring(raw), 'p:extLst')
    ns.notes_text_frame.text = 'V3: ' + t

def add_slide_transition(s, kind='push'):
    """Add a slide transition. kind: 'fade' | 'push' | 'wipe'"""
    tr = OxmlElement('p:transition')
    tr.set('spd', 'med')
    tr.set('advClick', '1')
    if kind == 'fade':
        tr.append(OxmlElement('p:fade'))
    elif kind == 'push':
        push = OxmlElement('p:push')
        push.set('dir', 'l')
        tr.append(push)
    else:
        wipe = OxmlElement('p:wipe')
        wipe.set('dir', 'l')
        tr.append(wipe)
    s._element.append(tr)

def add_fly_in(s, shape, delay_ms=0, duration_ms=500, dir='fromBottom'):
    """Add a fly-in entrance animation to a shape."""
    NS = {
        'p': 'http://schemas.openxmlformats.org/presentationml/2006/main',
        'a': 'http://schemas.openxmlformats.org/drawingml/2006/main',
    }
    # Ensure timing element exists
    timing = s._element.find('{http://schemas.openxmlformats.org/presentationml/2006/main}timing')
    if timing is None:
        timing = etree.SubElement(s._element, '{http://schemas.openxmlformats.org/presentationml/2006/main}timing')
    tnLst = timing.find('{http://schemas.openxmlformats.org/presentationml/2006/main}tnLst')
    if tnLst is None:
        tnLst = etree.SubElement(timing, '{http://schemas.openxmlformats.org/presentationml/2006/main}tnLst')
    par = tnLst.find('{http://schemas.openxmlformats.org/presentationml/2006/main}par')
    if par is None:
        par = etree.SubElement(tnLst, '{http://schemas.openxmlformats.org/presentationml/2006/main}par')
        cTn_root = etree.SubElement(par, '{http://schemas.openxmlformats.org/presentationml/2006/main}cTn')
        cTn_root.set('id', '1')
        cTn_root.set('dur', 'indefinite')
        cTn_root.set('restart', 'whenNotActive')
        cTn_root.set('nodeType', 'tmRoot')
        childTnLst = etree.SubElement(cTn_root, '{http://schemas.openxmlformats.org/presentationml/2006/main}childTnLst')
        seq = etree.SubElement(childTnLst, '{http://schemas.openxmlformats.org/presentationml/2006/main}seq')
        seq.set('concurrent', '1')
        seq.set('nextAc', 'seek')
        seqCTn = etree.SubElement(seq, '{http://schemas.openxmlformats.org/presentationml/2006/main}cTn')
        seqCTn.set('id', '2')
        seqCTn.set('dur', 'indefinite')
        seqCTn.set('nodeType', 'mainSeq')
        etree.SubElement(seqCTn, '{http://schemas.openxmlformats.org/presentationml/2006/main}childTnLst')

def build_reveal_timing(s):
    """Build a click-sequence animation for every shape named reveal_NN in order."""
    for el in list(s._element):
        if el.tag.endswith('}timing'):
            s._element.remove(el)

    shapes = [(sh, int(sh.name.split('_')[1]))
              for sh in s.shapes
              if re.fullmatch(r'reveal_\d+', sh.name)]
    if not shapes:
        return

    shapes.sort(key=lambda t: t[1])
    # group by order number — same number reveals together
    from itertools import groupby
    groups = [(k, [sh for sh, _ in g]) for k, g in groupby(shapes, key=lambda t: t[1])]

    NS_P = 'http://schemas.openxmlformats.org/presentationml/2006/main'
    NS_A = 'http://schemas.openxmlformats.org/drawingml/2006/main'

    def E(tag, **kw):
        el = etree.Element(f'{{{NS_P}}}{tag}')
        for k, v in kw.items(): el.set(k, str(v))
        return el

    timing  = E('timing')
    tnLst   = etree.SubElement(timing, f'{{{NS_P}}}tnLst')
    par_root = etree.SubElement(tnLst, f'{{{NS_P}}}par')
    cTn_root = etree.SubElement(par_root, f'{{{NS_P}}}cTn',
                                id='1', dur='indefinite', restart='whenNotActive', nodeType='tmRoot')
    cl_root  = etree.SubElement(cTn_root, f'{{{NS_P}}}childTnLst')
    seq      = etree.SubElement(cl_root, f'{{{NS_P}}}seq', concurrent='1', nextAc='seek')
    seqCTn   = etree.SubElement(seq, f'{{{NS_P}}}cTn',
                                id='2', dur='indefinite', nodeType='mainSeq')
    cl_seq   = etree.SubElement(seqCTn, f'{{{NS_P}}}childTnLst')

    gid = 10
    for click_idx, (order, shs) in enumerate(groups):
        par_click = etree.SubElement(cl_seq, f'{{{NS_P}}}par')
        cTn_click = etree.SubElement(par_click, f'{{{NS_P}}}cTn',
                                     id=str(gid), dur='indefinite', nodeType='clickEffect')
        gid += 1
        stCondLst = etree.SubElement(cTn_click, f'{{{NS_P}}}stCondLst')
        cond = etree.SubElement(stCondLst, f'{{{NS_P}}}cond', evt='onClick', delay='0')
        tn_ref = etree.SubElement(cond, f'{{{NS_P}}}tn', val='2')
        cl_click = etree.SubElement(cTn_click, f'{{{NS_P}}}childTnLst')

        for sh in shs:
            par_anim = etree.SubElement(cl_click, f'{{{NS_P}}}par')
            cTn_anim = etree.SubElement(par_anim, f'{{{NS_P}}}cTn',
                                        id=str(gid), dur='400', fill='hold')
            gid += 1
            stCond = etree.SubElement(etree.SubElement(cTn_anim, f'{{{NS_P}}}stCondLst'),
                                      f'{{{NS_P}}}cond', delay='0')
            anim_cl = etree.SubElement(cTn_anim, f'{{{NS_P}}}childTnLst')
            set_el  = etree.SubElement(anim_cl, f'{{{NS_P}}}set')
            cBhvr   = etree.SubElement(set_el, f'{{{NS_P}}}cBhvr')
            cTn_b   = etree.SubElement(cBhvr, f'{{{NS_P}}}cTn',
                                       id=str(gid), dur='1', fill='hold')
            gid += 1
            stCond2 = etree.SubElement(etree.SubElement(cTn_b, f'{{{NS_P}}}stCondLst'),
                                       f'{{{NS_P}}}cond', delay='0')
            tgt     = etree.SubElement(cBhvr, f'{{{NS_P}}}tgtEl')
            spTgt   = etree.SubElement(tgt, f'{{{NS_P}}}spTgt', spid=str(sh.shape_id))
            attn    = etree.SubElement(cBhvr, f'{{{NS_P}}}attrNameLst')
            etree.SubElement(attn, f'{{{NS_P}}}attrName').text = 'style.visibility'
            to_el   = etree.SubElement(set_el, f'{{{NS_P}}}to')
            etree.SubElement(to_el, f'{{{NS_A}}}strVal', val='visible')

    # prev/next wiring for seq
    prevCondLst = etree.SubElement(seq, f'{{{NS_P}}}prevCondLst')
    prev_cond   = etree.SubElement(prevCondLst, f'{{{NS_P}}}cond', evt='onPrevClick', delay='0')
    etree.SubElement(prev_cond, f'{{{NS_P}}}tn', val='2')
    s._element.append(timing)

